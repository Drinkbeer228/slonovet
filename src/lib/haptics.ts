/**
 * Виброотклик на действия: телефон «отвечает» на касание. Работает там, где браузер умеет вибрировать
 * (Android); на iPhone вибрации из браузера нет — вызовы тихо ничего не делают.
 * Вызывать только из обработчиков нажатий: без действия человека браузер вибрацию не пропустит.
 * Когда появится приложение (Capacitor) — вызов @capacitor/haptics встанет сюда, в buzz.
 */
function buzz(pattern: number | number[]) {
  try {
    if ('vibrate' in navigator) navigator.vibrate(pattern);
  } catch {
    /* вибрация — не повод ломать нажатие */
  }
}

export const haptics = {
  /** лёгкий щелчок: вкладка, шторка закрылась */
  tap: () => buzz(12),
  /** мягкий двойной: отправлено, отмечено */
  success: () => buzz([15, 30, 15]),
  /** заметный: просрочено, что-то не так */
  warning: () => buzz([30, 40, 30]),
  /** настойчивый: ошибка */
  error: () => buzz([40, 60, 40, 60, 40]),
};
