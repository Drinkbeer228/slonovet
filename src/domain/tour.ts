export function sectionTour(tab: string, role: Role): SectionTour | null {
  switch (tab) {
    case 'shift':
      return role === 'keeper' ? SHIFT_KEEPER : SHIFT_VIEW;
    case 'journal':
      return JOURNAL;
    case 'requests':
      return REQUESTS;
    case 'stock':
      return STOCK;
    case 'diet':
      return DIET;
    case 'users':
      return role === 'admin' || role === 'director' || role === 'manager' ? USERS : null;
    case 'move':
      return MOVE;
    default:
      return null;
  }
}

