import type { Role } from './types';

/**
 * Подсказки. Два вида:
 *  — знакомство при первом входе (INTRO): где что лежит — показывается само, один раз;
 *  — рассказ о разделе (SECTIONS): как там всё работает — по кнопке в Справке.
 * Поднять версию — и подсказки увидят заново все, кто уже входил (например, после нового раздела).
 */
export const INTRO_VERSION = 3;
export const SECTION_VERSION = 2;

export type TourTab = 'shift' | 'journal' | 'requests' | 'diet' | 'stock' | 'users' | 'move';

export interface TourStep {
  /** что подсветить: CSS-селектор; не указан — подсказка посередине */
  target?: string;
  /** какой раздел открыть перед шагом */
  tab?: TourTab;
  title: string;
  text: string;
  /** места нет на экране (например, нет дежурства) — шаг молча пропустить */
  optional?: boolean;
}

export interface SectionTour {
  /** показывать, только когда это есть на экране (рассказ о дежурстве — когда дежурство открыто) */
  when?: string;
  steps: TourStep[];
}

const menu = (text: string): TourStep => ({ target: '[data-tour="menu"]', title: 'Меню', text });
